a('right_assoc',r'(v^{\prime}u^{\prime})(uv)=v^{\prime}(u^{\prime}(uv))',r'\FormulaRefAuto{SemigroupAssociativityAxiom}[ax]{@sg,@vp,@up,@uv}')
a('inner_right_assoc',r'(u^{\prime}u)v=u^{\prime}(uv)',r'\FormulaRefAuto{SemigroupAssociativityAxiom}[ax]{@sg,@up,@u_a,@v_a}')
a('inner_right_sym',r'u^{\prime}(uv)=(u^{\prime}u)v',r'\FormulaRefAuto{a=b\vdash b=a}[thm]{@inner_right_assoc}')
a('ev',r'ev=v',r'\rAEa{\rRE{\rUE{@neutral},@v_a}}')
