a('v_exists',r'\exists v^{\prime}\in A\;(vv^{\prime}=e\land v^{\prime}v=e)',r'\FormulaRefAuto{SemigroupUnitsAtIdentityDef}[def]{@sg,@e,@neutral,@v}')
