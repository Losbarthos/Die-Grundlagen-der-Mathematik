a('eup',r'eu^{\prime}=u^{\prime}',r'\rAEa{\rRE{\rUE{@neutral},@up}}')
a('inner_left',r'v(v^{\prime}u^{\prime})=u^{\prime}',r'\rIE{@vv,@eup,@inner_left_sym}')
