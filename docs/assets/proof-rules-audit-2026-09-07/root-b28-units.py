a('vv',r'vv^{\prime}=e',r'\rAEa{\rAEb{@vw}}')
a('vpv',r'v^{\prime}v=e',r'\rAEb{\rAEb{@vw}}')
a('uv',r'uv\in A',r'\FormulaRefAuto{SemigroupClosureAxiom}[ax]{@sg,@u_a,@v_a}')
